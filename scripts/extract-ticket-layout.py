"""Builds lib/ticket-layout.ts from the owner's pawn ticket PDF.
Usage: python3 -I scripts/extract-ticket-layout.py <ticket.pdf> > lib/ticket-layout.ts
Every word is placed at the exact point position it has in the PDF."""
import json, os, sys, pymupdf

d = pymupdf.open(sys.argv[1])
# optional: per-word letter-spacing (pt) measured in the browser by scripts/measure-ticket-spacing.cjs
LS = json.load(open(sys.argv[2])) if len(sys.argv) > 2 and os.path.exists(sys.argv[2]) else {}
p = d[0]
W, H = p.rect.width, p.rect.height
FONT = {
    "Montserrat-Light": ("montserrat", 300, "normal"),
    "Montserrat-SemiBold": ("montserrat", 600, "normal"),
    "Montserrat-Bold": ("montserrat", 700, "normal"),
    "Montserrat-SemiBoldItalic": ("montserrat", 600, "italic"),
    "Montserrat-SemiBoldItali": ("montserrat", 600, "italic"),
    "Poppins-Light": ("poppins", 300, "normal"),
    "Poppins-SemiBold": ("poppins", 600, "normal"),
}
DROP = {"<BOLD>", "<", "BOLD>"}  # placeholders the system fills in
# per-word vertical correction (pt) so browser glyphs land where the PDF's do; measured by scripts/calibrate-ticket-y.py
YADJ = json.load(open(sys.argv[3])) if len(sys.argv) > 3 and os.path.exists(sys.argv[3]) else {}
words, slots, fields = [], [], []
for b in p.get_text("rawdict")["blocks"]:
    for l in b.get("lines", []):
        for s in l["spans"]:
            fam, wt, st = FONT[s["font"].split("+")[-1]]
            x0, y0, x1, y1 = s["bbox"]
            chars = s["chars"]
            i = 0
            while i < len(chars):
                if chars[i]["c"].isspace():
                    i += 1
                    continue
                j = i
                while j < len(chars) and not chars[j]["c"].isspace():
                    j += 1
                text = "".join(c["c"] for c in chars[i:j])
                if text in ("<BOLD>", "<"):  # first placeholder char = where the value starts
                    fields.append(dict(x=round(chars[i]["bbox"][0], 2), y=round(y0, 2), h=round(y1 - y0, 2), s=round(s["size"], 2)))
                if text not in DROP:
                    wd = dict(t=text, x=round(chars[i]["bbox"][0], 2), y=round(y0 - YADJ.get(str(len(words)), 0), 2), h=round(y1 - y0, 2),
                              s=round(s["size"], 2), f=fam, w=wt, i=st, pw=round(chars[j - 1]["bbox"][2] - chars[i]["bbox"][0], 2))
                    if str(len(words)) in LS:
                        wd["ls"] = LS[str(len(words))]
                    words.append(wd)
                # underscore runs inside this word = blanks to fill
                k = i
                while k < j:
                    if chars[k]["c"] == "_":
                        m = k
                        while m < j and chars[m]["c"] == "_":
                            m += 1
                        slots.append(dict(x=round(chars[k]["bbox"][0], 2), x2=round(chars[m - 1]["bbox"][2], 2), y=round(y0, 2), h=round(y1 - y0, 2)))
                        k = m
                    else:
                        k += 1
                i = j
rects = []
for dr in p.get_drawings():
    if dr["type"] == "s":
        r = dr["rect"]
        rects.append(dict(x=round(r.x0, 2), y=round(r.y0, 2), w=round(r.width, 2), h=round(r.height, 2), lw=round(dr["width"], 2)))
print("// GENERATED by scripts/extract-ticket-layout.py from the owner's pawn ticket PDF. Do not edit by hand.")
print("// All numbers are PDF points (1/72 in) from the top-left of an 8.5 x 6.5 in page.")
print(f"export const TICKET_PAGE = {{ w: {W}, h: {H} }};")
print("export type TicketWord = { t: string; x: number; y: number; h: number; s: number; f: 'montserrat' | 'poppins'; w: number; i: 'normal' | 'italic'; pw: number; ls?: number };")
print("export type TicketSlot = { x: number; x2: number; y: number; h: number };")
print("export type TicketRect = { x: number; y: number; w: number; h: number; lw: number };")
print("export const TICKET_WORDS: TicketWord[] = " + json.dumps(words, ensure_ascii=False) + ";")
print("/** Blank underscore runs in reading order: name, address, pesos in words, amount, interest %, appraised value. */")
print("export const TICKET_SLOTS: TicketSlot[] = " + json.dumps(slots) + ";")
print("/** Where the bold dates start: loan date, maturity date, redemption expiry. */")
print("export const TICKET_FIELDS: { x: number; y: number; h: number; s: number }[] = " + json.dumps(fields) + ";")
print("export const TICKET_RECTS: TicketRect[] = " + json.dumps(rects) + ";")
